"""
Agent C — Content & Solution Generation (Full Loop)
"""
import os
from agents.base import utcnow
from orchestrator.state import QuestionStateObject

from .question_gen import generate as gen_question
from .html_format import format_html
from .solution_arch import design_solution
from .code_gen import generate as gen_code
from .code_format import format_code
from .test_case_gen import generate_tests
from .sandbox_exec import execute_and_verify

async def run(state: QuestionStateObject) -> dict:
    q_id = state.get("question_id", "unknown")
    print(f"[Agent C] Starting generation for: {q_id}")

    blueprint = state.get("blueprint", {})
    language = state.get("requirements", {}).get("target_language", "python")
    template = state.get("client_config", {}).get("code_template", "")

    references = state.get("references", [])
    # Step 1: Content generation
    authoring_spec_ref = next((r for r in references if r.get("doc_type") == "AUTHORING_SPEC"), None)
    domain_refs = [r for r in references if r.get("doc_type") != "AUTHORING_SPEC"]
    if authoring_spec_ref:
        print(f"[Agent C] 1. Generating question with AUTHORING_SPEC: '{authoring_spec_ref.get('title')}' + {len(domain_refs)} domain refs...")
    else:
        print(f"[Agent C] 1. Generating question (using {len(references)} references, NO authoring spec)...")
    question = await gen_question(blueprint, references=references)
    
    # Step 2: HTML Formatting
    print("[Agent C] 2. Formatting HTML...")
    # Prefer existing built-in platform HTML if generated by gen_question
    formatted_html = question.get("description_html") or await format_html(question.get("description_markdown", ""))
    question["description_html"] = formatted_html

    # Step 3: Test Case Generation
    print("[Agent C] 3. Generating test cases...")
    test_cases = await generate_tests(question)
    
    # Internal Retry Loop (Configurable via env var, default 3)
    max_retries = int(os.environ.get("MAX_INTERNAL_RETRIES", "3"))
    passed = False
    feedback = ""
    sandbox_res = {}
    solution_arch = {}
    formatted_code = ""
    attempt = 0
    
    for attempt in range(1, max_retries + 1):
        print(f"\n[Agent C] Attempt {attempt}/{max_retries}...")
        
        blueprint_with_feedback = dict(blueprint)
        if feedback:
            blueprint_with_feedback["previous_error"] = feedback

        print("  - Designing architecture...")
        solution_arch = await design_solution(question, blueprint_with_feedback)

        print("  - Writing code...")
        lang_stub = question.get("code_stubs", {}).get(language.lower(), template)
        effective_template = lang_stub if lang_stub else template
        code_result = await gen_code(question, solution_arch, language, effective_template)
        formatted_code = format_code(code_result.get("solution_code", ""), language)
        
        print("  - Executing in Sandbox...")
        try:
            sandbox_res = await execute_and_verify(formatted_code, language, test_cases)
        except Exception as e:
            print(f"  ❌ Sandbox Execution Exception: {e}")
            sandbox_res = {"passed": False, "output": str(e), "unverified": False}
        
        if sandbox_res.get("passed"):
            print("  ✅ All sandbox tests passed!")
            passed = True
            break
        else:
            feedback = sandbox_res.get("output", "Unknown error")
            print(f"  ❌ Sandbox Failed! Error: {feedback.strip().splitlines()[-1] if feedback else 'None'}")
            print("  🔄 Retrying...")

    retry_count = (attempt - 1) if passed else attempt

    return {
        "current_agent": "agent_c",
        "updated_at": utcnow(),
        "question": question,
        "html": {
            "formatted_question": formatted_html,
            "html_valid": bool(formatted_html and len(formatted_html) > 0),
            "validation_errors": [],
        },
        "code": {"solution": formatted_code, "language": language},
        "execution": {
            "all_passed": passed,
            "unverified": sandbox_res.get("unverified", language.lower() != "python"),
            "output": sandbox_res.get("output", ""),
            "solution_correctness_score": 1.0 if passed else 0.0,
        },
        "test_cases": test_cases,
        "code_stubs": question.get("code_stubs", {}),
        "generated_question": question,
        "solution_architecture": solution_arch,
        "solution_code": formatted_code,
        "sandbox_passed": passed,
        "internal_retry_count": retry_count,
    }
